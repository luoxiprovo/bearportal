function main(): Promise<void> {
  const command = process.argv[2];
  if (command === "prepare") return Promise.resolve(prepare());
  if (command === "migrate") return migrateCommand();
  if (command === "reset") return resetCommand();
  if (command === "bootstrap") return bootstrapCommand();
  if (command === "start") return Promise.resolve(start());
  if (command === "auth-configure") return configureIdentity(envFile,process.argv.slice(3));
  if (command === "inventory") return inventoryCommand();
  if (command === "login") return loginCommand();
  if (command === "token") return tokenCommand();
  if (command === "walk") return walk();
  console.error("Usage: tsx scripts/local-trial.ts prepare|migrate|reset|bootstrap|start|login|inventory|auth-configure|token|walk");
  process.exit(1);
}

main().catch((error: unknown) => {
  const message = error instanceof Error ? error.message : "The trial command failed.";
  console.error(message.replace(/postgres(?:ql)?:\/\/\S+/gi, "postgres://[redacted]"));
  process.exit(1);
});

function prepare(): void {
  if (process.env.BEARPORTAL_ENV === "production") {
    throw new Error("The local trial refuses BEARPORTAL_ENV=production.");
  }
  mkdirSync(trialDir, { recursive: true, mode: 0o700 });
  mkdirSync(join(trialDir, "secrets"), { recursive: true, mode: 0o700 });
  chmodSync(trialDir, 0o700);
  chmodSync(join(trialDir, "secrets"), 0o700);
  if (existsSync(envFile)) {
    console.log("Trial env already exists. Existing keys were left in place.");
    return;
  }
  const pair = generateKeyPairSync("rsa", {
    modulusLength: 2048,
    publicKeyEncoding: { type: "spki", format: "pem" },
    privateKeyEncoding: { type: "pkcs8", format: "pem" },
  });
  writeFileSync(privateKeyFile, pair.privateKey, { mode: 0o600 });
  writeFileSync(publicKeyFile, pair.publicKey, { mode: 0o644 });
  chmodSync(privateKeyFile, 0o600);
  const schedulerToken = randomBytes(24).toString("base64url");
  const secretKey = randomBytes(32).toString("hex");
  const body = [
    "# Generated by pnpm trial:prepare. Gitignored. Local development only.",
    "# The development API reads BEARPORTAL_JWT_PRIVATE_KEY_FILE only to sign browser registration. scripts/local-trial.ts uses the same key to mint test tokens.",
    "DATABASE_URL=postgres://bearportal_app:bearportal_app@127.0.0.1:5432/bearportal",
    "MIGRATION_DATABASE_URL=postgres://bearportal:bearportal@127.0.0.1:5432/bearportal",
    `BEARPORTAL_SECRET_KEY=${secretKey}`,
    `BEARPORTAL_JWT_PUBLIC_KEY_FILE=${publicKeyFile}`,
    `BEARPORTAL_JWT_PRIVATE_KEY_FILE=${privateKeyFile}`,
    "BEARPORTAL_JWT_ISSUER=https://test.bearportal.local",
    "BEARPORTAL_JWT_AUDIENCE=bearportal-test",
    `BEARPORTAL_SECRETS_DIR=${join(trialDir, "secrets")}`,
    "BEARPORTAL_API_ORIGIN=http://127.0.0.1:8088",
    "BEARPORTAL_BIND_HOST=127.0.0.1",
    "PORT=8088",
    "BEARPORTAL_ENV=development",
    "BOOTSTRAP_ADMIN_SUBJECT=bootstrap-admin",
    "BOOTSTRAP_ADMIN_EMAIL=admin@recovery-bearportal.com",
    "BEARPORTAL_ALLOW_TEST_ISSUER=1",
    `BEARPORTAL_SCHEDULER_TOKEN=${schedulerToken}`,
    "",
  ].join("\n");
  writeFileSync(envFile, body, { mode: 0o600 });
  chmodSync(envFile, 0o600);
  console.log("Wrote .data/trial/env and a local test key pair. These files are gitignored.");
}

